import math, unicodedata
def est_line_inches(text, size_pt):
    w=0.0
    for ch in text:
        ea=unicodedata.east_asian_width(ch)
        w += (1.0 if ea in ("F","W","A") else 0.55)*size_pt/72.0
    return w

def body_bottom_estimate(body, width_in=8.9, y0=1.15):
    y=y0
    for item in body:
        lvl, text = item[0], item[1]
        size = item[2] if len(item)>2 else (21 if lvl==0 else 18)
        avail = width_in - lvl*0.3
        lines = max(1, math.ceil(est_line_inches(text, size)/avail))
        y += lines*size*1.42/72.0
    return y

