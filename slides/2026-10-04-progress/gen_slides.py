def add_image(slide, path, x, y, w=None, h=None, max_bottom=5.42):
    im = Image.open(path); aw, ah = im.size
    if w and not h: h = w * ah / aw
    if h and not w: w = h * aw / ah
    if y + h > max_bottom:          # 下端からはみ出す場合は縮小
        h = max_bottom - y
        w = h * aw / ah
    slide.shapes.add_picture(path, Inches(x), Inches(y), Inches(w), Inches(h))
    return w, h

def add_textbox(slide, x, y, w, h, lines, size=21, color=None, bold=False):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame; tf.word_wrap = True
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        r = p.add_run(); r.text = line
        r.font.size = Pt(size); r.font.name = "Arial"; r.font.bold = bold
        if color is not None: r.font.color.rgb = color
    return tb

